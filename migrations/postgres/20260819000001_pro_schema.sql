CREATE TABLE device_shares (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
    device_row_id BIGINT NOT NULL,
    device_lifecycle TEXT NOT NULL CHECK (device_lifecycle ~ '^[0-9a-f]{32}$'),
    device_id TEXT NOT NULL CHECK (length(device_id) BETWEEN 1 AND 100),
    from_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    to_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    permission TEXT NOT NULL CHECK (permission IN ('view_only', 'full_control')),
    status TEXT NOT NULL CHECK (status IN ('pending', 'accepted', 'rejected')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(device_row_id, to_user_id),
    CHECK(from_user_id <> to_user_id),
    FOREIGN KEY(device_row_id, device_lifecycle, device_id)
        REFERENCES devices(id, management_generation, device_id)
        ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE INDEX idx_device_shares_recipient_status_id ON device_shares(to_user_id, status, id);
CREATE INDEX idx_device_shares_owner_device_status ON device_shares(from_user_id, device_row_id, status);
CREATE INDEX idx_device_shares_device_recipient ON device_shares(device_id, to_user_id);

