CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE CHECK (length(username) BETWEEN 1 AND 100),
    password_hash VARCHAR(255) NOT NULL,
    email VARCHAR(255),
    role VARCHAR(50) NOT NULL DEFAULT 'user',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    token_version BIGINT NOT NULL DEFAULT 0 CHECK (token_version BETWEEN 0 AND 9007199254740991),
    oauth_provider VARCHAR(100),
    oauth_subject VARCHAR(255),
    last_login_at TIMESTAMP,
    address_book_version BIGINT NOT NULL DEFAULT 0 CHECK (address_book_version BETWEEN 0 AND 9007199254740991),
    failed_login_count BIGINT NOT NULL DEFAULT 0 CHECK (failed_login_count >= 0),
    locked_until TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (id BETWEEN 1 AND 9007199254740991)
);
CREATE INDEX idx_users_email ON users(email);
CREATE INDEX idx_users_oauth ON users(oauth_provider, oauth_subject);
CREATE INDEX idx_users_last_login_at ON users(last_login_at);
CREATE INDEX idx_users_token_version ON users(token_version);
CREATE INDEX idx_users_locked_until ON users(locked_until) WHERE locked_until IS NOT NULL;

