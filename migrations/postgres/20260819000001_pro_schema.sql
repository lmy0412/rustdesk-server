CREATE TABLE devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guid BYTEA NOT NULL UNIQUE,
    uuid BYTEA NOT NULL,
    pk BYTEA NOT NULL,
    device_id VARCHAR(100) NOT NULL UNIQUE,
