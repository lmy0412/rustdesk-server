CREATE FUNCTION rustdesk_validate_group() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    ancestor_depth INTEGER := 0;
    subtree_depth INTEGER := 1;
BEGIN
    IF TG_OP = 'UPDATE' AND NEW.owner_user_id <> OLD.owner_user_id THEN
        RAISE EXCEPTION 'group_owner_immutable';
    END IF;
    IF NEW.parent_group_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM groups WHERE id = NEW.parent_group_id AND owner_user_id = NEW.owner_user_id
    ) THEN
        RAISE EXCEPTION 'group_parent_owner_mismatch';
    END IF;
    IF NEW.parent_group_id = NEW.id OR (NEW.parent_group_id IS NOT NULL AND EXISTS (
        WITH RECURSIVE ancestors(id, depth) AS (
            SELECT NEW.parent_group_id, 1
            UNION ALL
            SELECT parent.parent_group_id, ancestors.depth + 1
            FROM groups parent JOIN ancestors ON parent.id = ancestors.id
            WHERE parent.parent_group_id IS NOT NULL AND ancestors.depth <= 256
        )
        SELECT 1 FROM ancestors WHERE id = NEW.id
    )) THEN
        RAISE EXCEPTION 'group_cycle';
    END IF;
    IF NEW.parent_group_id IS NOT NULL THEN
        WITH RECURSIVE ancestors(id, depth) AS (
            SELECT NEW.parent_group_id, 1
            UNION ALL
            SELECT parent.parent_group_id, ancestors.depth + 1
            FROM groups parent JOIN ancestors ON parent.id = ancestors.id
            WHERE parent.parent_group_id IS NOT NULL AND ancestors.depth <= 256
        )
        SELECT COALESCE(MAX(depth), 0) INTO ancestor_depth FROM ancestors;
    END IF;
    IF TG_OP = 'UPDATE' THEN
        WITH RECURSIVE descendants(id, depth) AS (
            SELECT NEW.id, 1
            UNION ALL
            SELECT child.id, descendants.depth + 1
            FROM groups child JOIN descendants ON child.parent_group_id = descendants.id
            WHERE descendants.depth <= 256
        )
        SELECT COALESCE(MAX(depth), 1) INTO subtree_depth FROM descendants;
    END IF;
    IF ancestor_depth + subtree_depth > 256 THEN
        RAISE EXCEPTION 'group_depth_exceeded';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER group_integrity BEFORE INSERT OR UPDATE ON groups
FOR EACH ROW EXECUTE FUNCTION rustdesk_validate_group();

CREATE FUNCTION rustdesk_validate_device() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'UPDATE' AND OLD.management_generation IS NOT NULL
       AND NEW.management_generation <> OLD.management_generation THEN
        RAISE EXCEPTION 'device_management_generation_immutable';
    END IF;
    IF NEW.group_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM groups WHERE id = NEW.group_id AND owner_user_id = NEW.owner_user_id
    ) THEN
        RAISE EXCEPTION 'device_group_owner_mismatch';
    END IF;
    IF TG_OP = 'UPDATE' AND NEW.owner_user_id IS DISTINCT FROM OLD.owner_user_id
       AND EXISTS (SELECT 1 FROM device_tags WHERE device_row_id = OLD.id) THEN
        RAISE EXCEPTION 'device_owner_change_with_tags';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER device_integrity BEFORE INSERT OR UPDATE ON devices
FOR EACH ROW EXECUTE FUNCTION rustdesk_validate_device();

CREATE FUNCTION rustdesk_validate_tag() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.owner_user_id <> OLD.owner_user_id THEN
        RAISE EXCEPTION 'tag_owner_immutable';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER tag_integrity BEFORE UPDATE ON tags
FOR EACH ROW EXECUTE FUNCTION rustdesk_validate_tag();

CREATE FUNCTION rustdesk_validate_device_tag() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM devices d JOIN tags t ON t.id = NEW.tag_id
        WHERE d.id = NEW.device_row_id AND d.owner_user_id IS NOT NULL
          AND d.owner_user_id = t.owner_user_id
    ) THEN
        RAISE EXCEPTION 'device_tag_owner_mismatch';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER device_tag_integrity BEFORE INSERT OR UPDATE ON device_tags
FOR EACH ROW EXECUTE FUNCTION rustdesk_validate_device_tag();

CREATE FUNCTION rustdesk_validate_share() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM devices WHERE id = NEW.device_row_id
          AND management_generation = NEW.device_lifecycle
          AND device_id = NEW.device_id AND owner_user_id = NEW.from_user_id
    ) THEN
        RAISE EXCEPTION 'device_share_owner_mismatch';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER device_share_integrity BEFORE INSERT OR UPDATE ON device_shares
FOR EACH ROW EXECUTE FUNCTION rustdesk_validate_share();

CREATE FUNCTION rustdesk_validate_address_book_change() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE previous_version BIGINT;
BEGIN
    IF TG_OP <> 'INSERT' THEN
        RAISE EXCEPTION 'address_book_change_immutable';
    END IF;
    SELECT COALESCE(MAX(version), 0) INTO previous_version
      FROM address_book_changes WHERE user_id = NEW.user_id;
    IF previous_version <> NEW.version - 1 OR NOT EXISTS (
        SELECT 1 FROM users WHERE id = NEW.user_id AND address_book_version = NEW.version
    ) THEN
        RAISE EXCEPTION 'address_book_change_not_contiguous';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER address_book_change_insert_valid BEFORE INSERT ON address_book_changes
FOR EACH ROW EXECUTE FUNCTION rustdesk_validate_address_book_change();
CREATE TRIGGER address_book_change_immutable BEFORE UPDATE OR DELETE ON address_book_changes
FOR EACH ROW EXECUTE FUNCTION rustdesk_validate_address_book_change();
